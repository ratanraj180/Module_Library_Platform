async function seed() {
  try {
    await mongoose.connect(config.MONGO_URI);
    console.log('[seed] MongoDB connected');

    console.log('[seed] Clearing Users, Modules, Components, Versions, Reviews...');
    await Review.deleteMany({});
    await Version.deleteMany({});
    await Module.deleteMany({});
    await Component.deleteMany({});
    await User.deleteMany({});
    console.log('[seed] Collections cleared');

    const [admin, developer] = await User.create([
      {
        name: 'Admin User',
        email: 'admin@test.com',
        password: 'password123',
        role: 'admin',
      },
      {
        name: 'Developer User',
        email: 'dev@test.com',
        password: 'password123',
        role: 'developer',
      },
    ]);
    console.log('[seed] Created users:');
    console.log(`  - admin       : ${admin.email}`);
    console.log(`  - developer   : ${developer.email}`);

    // Seed original Modules
    console.log('[seed] Seeding original modules...');
    for (const mod of mockModules) {
      const created = await Module.create({
        title: mod.title,
        description: mod.description,
        category: mod.category,
        technology: mod.technology,
        repositoryUrl: mod.repositoryUrl,
        currentVersion: mod.currentVersion,
        downloadCount: mod.downloadCount,
        owner: developer._id,
        status: mod.status,
        fileUrl: mod.status === 'approved' ? `uploads/sample-${mod.title.toLowerCase().replace(/ /g, '-')}.zip` : undefined,
      });

      if (mod.status === 'approved') {
        await Version.create({
          module: created._id,
          versionNumber: '1.0.0',
          changelog: 'Initial seed release',
          uploadedBy: developer._id,
          repositoryUrl: mod.repositoryUrl,
        });

        await Review.create({
          module: created._id,
          reviewer: admin._id,
          status: 'approved',
          comment: 'Approved during seed.',
        });
      }
    }

    // Seed Marketplace Components
    console.log('[seed] Seeding marketplace components...');
    for (const comp of mockComponents) {
      await Component.create({
        title: comp.title,
        description: comp.description,
        category: comp.category,
        tags: comp.tags,
        dependencies: comp.dependencies,
        installation: comp.installation,
        frontendCode: comp.frontendCode,
        backendCode: comp.backendCode,
        documentation: comp.documentation,
        usage: comp.usage,
        status: comp.status,
        currentVersion: comp.currentVersion,
        downloadCount: comp.downloadCount,
        owner: developer._id
      });
    }

    console.log('\n[seed] Seed completed successfully');
    console.log('[seed] Test accounts (password: password123):');
    console.log(`  - Developer: ${developer.email}`);
    console.log(`  - Admin    : ${admin.email}`);
  } catch (err) {
    console.error('[seed] Seed failed:', err);
  } finally {
    await mongoose.disconnect();
    console.log('[seed] MongoDB disconnected');
  }
}

